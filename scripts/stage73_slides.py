#!/usr/bin/env python
"""ステージ73: 最終提案手法 F1 の発表資料の数値(ステージ72 の集計から作る。新しい計算はしない)。

``results/stage72/summary.json``(本判定)と ``addendum.json``(追補)を読み、数値を書式化して
``results/stage73/slides_numbers.md`` を書く。手で数値を写さない(転記の誤りを避ける)。

    uv run python scripts/stage73_slides.py
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

S72 = Path("results/stage72")
OUT = Path("results/stage73")


def ci(t: list[float]) -> str:
    return f"{t[0]:+.3f} [{t[1]:+.3f}, {t[2]:+.3f}]"


def sym(s: list[int]) -> str:
    return " ".join({1: "+", -1: "−", 0: "0"}[int(v)] for v in s)


def main() -> None:  # noqa: PLR0915
    sm: dict[str, Any] = json.loads((S72 / "summary.json").read_text(encoding="utf-8"))
    ad: dict[str, Any] = json.loads((S72 / "addendum.json").read_text(encoding="utf-8"))
    r, a = sm["res"], ad["res"]
    if sm["adopted"] != "f1":
        raise ValueError(f"ステージ72 の採用が F1 でない: {sm['adopted']}")
    f1 = {c: r[f"f1|{c}"] for c in ("c2", "c1")}
    s1 = {c: r[f"s1|{c}"]["m"] for c in ("c2", "c1")}
    a2 = {c: a[f"a2|{c}"]["m"] for c in ("c2", "c1")}
    out = ["# 発表資料の数値(最終版: F1 事後アンサンブル、ステージ73)", "",
           "**このファイルが最新。** `results/stage65/slides_numbers.md` と `results/stage69/pa"
           "per_tables.md` "
           "はステージ69 の設定(旧)の数値。すべて `results/stage72/summary.json`・`addendum.jso"
           "n` から"
           "`scripts/stage73_slides.py` で作った(手で写していない)。", "",
           "## 最終提案手法(ステージ72 で事前の 4 条件を満たして採用)", "",
           "- **コスト**: 再建企業 72 社の c± = 1/s(ε0 なし、残余は 10³ で上限)。評価差額金だけ"
           "凍結し、"
           "非支配株主持分は動かす",
           "- **輸送**: 片側不均衡 OT(τ1 = 0.05、ε = 0.001)。候補 S(i) = 行の確率の上位(累積 0."
           "9 まで、"
           f"最大 10 社)。統合する企業数は中央値 {f1['c2']['multi']:.2f} 社",
           "- **生成(事後アンサンブル)**: 候補 y_j ごとに 𝓕⁺ の上の凸 QP を解き、輸送確率 p̃ で"
           "凸結合する。y* = Σ_j p̃_ij QP(y_j)",
           "- **制約 𝓕⁺**: s47_final + 現金の下限 0.117 + 負債の上限 L(y) ≤ (1 − 10⁻⁶) max(2 L(x), "
           "0.01 A(x))",
           f"- **λ**: class 1 の 128 社だけで較正(λ̃*_0 = {sm['star']['f1']:g})、class 2 に同じ λ。"
           "払込資本の m = 10(事後選択)", "",
           "## 主張 A: 従来設定(ステージ69)より、両 class で純資産の改善が有意に高い", "",
           "| | class 2: 従来 → F1 | class 1: 従来 → F1 |", "|---|---|---|",
           f"| 純資産の改善 | {s1['c2']['nai']:.3f} → **{f1['c2']['m']['nai']:.3f}**(差 "
           f"{ci(f1['c2']['vs']['nai'])}) | {s1['c1']['nai']:.3f} → **{f1['c1']['m']['nai']:.3f}**"
           f"(差 {ci(f1['c1']['vs']['nai'])}) |",
           f"| 債務超過の解消率 | {s1['c2']['res']:.2f} → {f1['c2']['m']['res']:.2f} "
           f"| {s1['c1']['res']:.2f} → {f1['c1']['m']['res']:.2f} |",
           f"| 符号付き順位相関 | {s1['c2']['rho']:+.3f} → {f1['c2']['m']['rho']:+.3f}(差 "
           f"{ci(f1['c2']['vs']['rho'])}、有意でない) | {s1['c1']['rho']:+.3f} → "
           f"{f1['c1']['m']['rho']:+.3f}(差 {ci(f1['c1']['vs']['rho'])}、有意でない) |",
           f"| 変更された科目数 | {s1['c2']['n_changed']:.0f} → {f1['c2']['m']['n_changed']:.0f}"
           f"(実データ 16) | {s1['c1']['n_changed']:.0f} → {f1['c1']['m']['n_changed']:.0f}"
           "(実データ 14) |",
           f"| 15 項目の違反 | {s1['c2']['viol']} → {f1['c2']['m']['viol']} "
           f"| {s1['c1']['viol']} → {f1['c1']['m']['viol']} |", "",
           "- 順位相関の点推定は、両 class とも従来より低い(有意ではない)", "",
           "## 主張 B: 同じ新設計の 1 社選択(argmax)に対して、有意に優れるのは class 1 の順位相"
           "関だけ",
           "", "| | class 2: 1 社選択 / F1 | 差 [95%] | class 1: 1 社選択 / F1 | 差 [95%] |",
           "|---|---|---|---|---|"]
    fa = {c: a[f"f1|{c}"] for c in ("c2", "c1")}
    out += [f"| 純資産の改善 | {a2['c2']['nai']:.3f} / {fa['c2']['m']['nai']:.3f} "
            f"| {ci(fa['c2']['vs_a2']['nai'])} | {a2['c1']['nai']:.3f} /"
            f" {fa['c1']['m']['nai']:.3f} "
            f"| {ci(fa['c1']['vs_a2']['nai'])} |",
            f"| 符号付き順位相関 | {a2['c2']['rho']:+.3f} / {fa['c2']['m']['rho']:+.3f} "
            f"| {ci(fa['c2']['vs_a2']['rho'])} | {a2['c1']['rho']:+.3f} / "
            f"**{fa['c1']['m']['rho']:+.3f}** | **{ci(fa['c1']['vs_a2']['rho'])}** |",
            f"| 払込資本を減らした割合 | {a2['c2']['paid_dec']:.0%} /"
            f" {fa['c2']['m']['paid_dec']:.0%} "
            f"| — | {a2['c1']['paid_dec']:.0%} / {fa['c1']['m']['paid_dec']:.0%} | — |", "",
            "- 純資産の改善に有意な差はない。class 2 の順位相関は F1 のほうが低い(有意でない)",
            "- 解釈(未検証): 1 社への射影はその企業に固有の動きを持ち込む。上位候補(約 7 社)へ"
            "の最適解を"
            "平均すると、それが打ち消され、再建群に共通する科目の動きが残る", "",
            "## 主張 C: 先に混ぜる(QP(Σ p̃ y_j))と後で混ぜる(Σ p̃ QP(y_j)、F1)の違い(同じ S(i))", "",
            "| class | 方法 | 目標: ちょうど 0 | 目標: 貸借の残差 | 目標: AUC | 終点: 0 の科目数 "
            "| 終点: 残差 | 順位相関(従来との差の記号) |", "|---|---|---:|---:|---:|---:|---:|---|"]
    for c in ("c2", "c1"):
        for st, lab in (("pre05", "先に L2 重心"), ("pre05m1", "先に重み付き中央値(M1)"),
                        ("f1", "**F1**")):
            x = r[f"{st}|{c}"]
            out.append(f"| {c} | {lab} | {x['t_zero']:.2f} | {x['t_resid']:.1e} | {x['t_auc']:.3f} "
                       f"| {x['e_zero']:.2f} | {x['e_resid']:.0e} | {x['m']['rho']:+.3f}"
                       f"({sym(x['vs']['sign'])}) |")
    out += ["", "- 先に混ぜると、**目標**がキメラになる(L2 重心はゼロが消え、M1 は貸借が崩れる)",
            "- **QP の後の終点**は、どの方法でも貸借が一致し(10⁻¹⁴ 以下)、ゼロも残る。F1 の終点"
            "のゼロは"
            "むしろ少ない(候補ごとに動いた科目の和集合)が、健全企業(6.70)以上",
            "- class 1 の順位相関は、先に混ぜる 2 つが従来より有意に劣り(記号の 3 つ目が「−」)"
            "、F1 は劣らない。"
            "**F1 との直接の比較はしていない。** class 2 では先に L2 重心のほうが F1 より順位相"
            "関が高い",
            "- F1 の終点は 𝓕⁺ の実行可能解の凸結合なので、𝓕⁺ の全制約と貸借一致を満たす(𝓕⁺ が凸"
            ")", "",
            "## 主張 D: τ1 の感度(F1、すべて違反 0)", "",
            "| τ1(統合した企業数 c2 / c1) | 純資産の改善 c2 / c1 | 順位相関 c2 / c1 | 記号 c2 /"
            " c1 |",
            "|---|---|---|---|"]
    for st, lab in (("f1t001", "0.01"), ("f1", "**0.05(事前に記録した代表値)**"),
                    ("f1t01", "0.1"), ("f1bal", "∞(バランス OT、上位 10 社)")):
        x2, x1 = a[f"{st}|c2"], a[f"{st}|c1"]
        out.append(f"| {lab}({x2['multi']:.2f} / {x1['multi']:.2f}) | {x2['m']['nai']:.3f} / "
                   f"{x1['m']['nai']:.3f} | {x2['m']['rho']:+.3f} / {x1['m']['rho']:+.3f} "
                   f"| {sym(x2['vs']['sign'])} / {sym(x1['vs']['sign'])} |")
    out += ["", "- 「τ1 = 0.05 が最良」とは書かない。τ1 = 0.01(ほぼ 1 社)では class 1 の順位相"
                "関が崩れる"
            "(1 社選択と同じ)。複数企業を統合する τ1 = 0.05・0.1 は、計算した条件(違反 0・統合 "
            "≥ 3・"
            "終点のゼロと貸借・主指標)を満たす(τ1 = 0.1 の目標の AUC は未計算)",
            "- バランス OT の F1 は違反 0 で、主指標が従来より劣らない。class 1 では有意に優れ"
            "る指標がない", "",
            "## 限界", "",
            f"- 払込資本を減らす企業の割合が増える: class 2 で {s1['c2']['paid_dec']:.0%} → "
            f"{f1['c2']['m']['paid_dec']:.0%}(実データ 36%)、class 1 で"
            f" {s1['c1']['paid_dec']:.0%} → "
            f"{f1['c1']['m']['paid_dec']:.0%}(実データ 23%)",
            "- 払込資本の m = 10 は事後選択。m = 1 の F1 は採用基準を満たさない(class 2 で 1 社"
            "が項目 3・4 "
            "に違反、class 1 で純資産の改善と順位相関が劣る)",
            "- 順位相関の点推定は従来より低い(有意でない)",
            "- 15 項目のうち項目 3・4・11 は 𝓕 の制約に入っていない(終点で検査)", ""]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "slides_numbers.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
